CREATE TABLE apontamento_jornada (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     funcionario_id BIGINT NOT NULL,
                                     grupo_producao_id BIGINT NOT NULL,
                                     inicio_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                                     fim_em TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                                     intervalo_minutos INTEGER NOT NULL DEFAULT 0,
                                     minutos_liquidos INTEGER NOT NULL,

                                     CONSTRAINT fk_apontamento_jornada_funcionario
                                         FOREIGN KEY (funcionario_id)
                                             REFERENCES funcionario(id)
                                             ON DELETE RESTRICT,

                                     CONSTRAINT fk_apontamento_jornada_grupo
                                         FOREIGN KEY (grupo_producao_id)
                                             REFERENCES grupo_producao(id)
                                             ON DELETE RESTRICT,

                                     CONSTRAINT ck_apontamento_jornada_horario
                                         CHECK (fim_em > inicio_em),

                                     CONSTRAINT ck_apontamento_jornada_precisao_minuto
                                         CHECK (
                                             date_trunc('minute', inicio_em) = inicio_em
                                                 AND date_trunc('minute', fim_em) = fim_em
                                             ),

                                     CONSTRAINT ck_apontamento_jornada_intervalo
                                         CHECK (
                                             intervalo_minutos >= 0
                                                 AND intervalo_minutos <= FLOOR(
                                                     EXTRACT(EPOCH FROM (fim_em - inicio_em)) / 60
                                                                          )
                                             ),

                                     CONSTRAINT ck_apontamento_jornada_liquido
                                         CHECK (
                                             minutos_liquidos >= 0
                                                 AND minutos_liquidos = FLOOR(
                                                     EXTRACT(EPOCH FROM (fim_em - inicio_em)) / 60
                                                                        )::INTEGER - intervalo_minutos
)
    );

CREATE INDEX idx_apontamento_jornada_funcionario_periodo
    ON apontamento_jornada (funcionario_id, inicio_em, fim_em);

CREATE INDEX idx_apontamento_jornada_grupo_data
    ON apontamento_jornada (grupo_producao_id, inicio_em);