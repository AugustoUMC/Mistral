CREATE TABLE grupo_producao (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                nome VARCHAR(255) NOT NULL UNIQUE,
                                ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE produto (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         codigo VARCHAR(255) NOT NULL UNIQUE,
                         descricao VARCHAR(255) NOT NULL,
                         ean VARCHAR(255),
                         dun VARCHAR(255),
                         caixa_master INTEGER,
                         diametro_cm NUMERIC(10,2),
                         altura NUMERIC(10,2),
                         preco_bruto NUMERIC(12,2),
                         imagem VARCHAR(500)
);

CREATE TABLE meta_producao (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               grupo_producao_id BIGINT NOT NULL,
                               produto_id BIGINT NOT NULL,
                               quantidade_meta INTEGER NOT NULL,
                               CONSTRAINT fk_meta_grupo
                                   FOREIGN KEY (grupo_producao_id)
                                       REFERENCES grupo_producao(id),
                               CONSTRAINT fk_meta_produto
                                   FOREIGN KEY (produto_id)
                                       REFERENCES produto(id)
);