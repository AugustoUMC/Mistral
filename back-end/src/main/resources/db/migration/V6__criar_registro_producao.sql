
CREATE TABLE registro_producao (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   grupo_producao_id BIGINT NOT NULL,
                                   produto_id BIGINT NOT NULL,

                                   data_producao DATE NOT NULL,
                                   quantidade_produzida INTEGER NOT NULL,
                                   quantidade_defeituosa INTEGER NOT NULL DEFAULT 0,

                                   CONSTRAINT fk_registro_grupo
                                       FOREIGN KEY (grupo_producao_id)
                                           REFERENCES grupo_producao(id),

                                   CONSTRAINT fk_registro_produto
                                       FOREIGN KEY (produto_id)
                                           REFERENCES produto(id),

                                   CONSTRAINT ck_quantidade_produzida
                                       CHECK (quantidade_produzida > 0),

                                   CONSTRAINT ck_quantidade_defeituosa
                                       CHECK (
                                           quantidade_defeituosa >= 0
                                               AND quantidade_defeituosa <= quantidade_produzida
                                           )
);
