CREATE TABLE alocacao_funcionario_grupo (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            funcionario_id BIGINT NOT NULL,
                                            grupo_producao_id BIGINT NOT NULL,
                                            data_inicio DATE NOT NULL,
                                            data_fim DATE,

                                            CONSTRAINT fk_alocacao_funcionario
                                                FOREIGN KEY (funcionario_id)
                                                    REFERENCES funcionario(id)
                                                    ON DELETE RESTRICT,

                                            CONSTRAINT fk_alocacao_grupo
                                                FOREIGN KEY (grupo_producao_id)
                                                    REFERENCES grupo_producao(id)
                                                    ON DELETE RESTRICT,

                                            CONSTRAINT ck_alocacao_periodo
                                                CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE UNIQUE INDEX uk_alocacao_funcionario_grupo_atual
    ON alocacao_funcionario_grupo (funcionario_id, grupo_producao_id)
    WHERE data_fim IS NULL;

CREATE INDEX idx_alocacao_funcionario_historico
    ON alocacao_funcionario_grupo (funcionario_id, data_inicio DESC);

CREATE INDEX idx_alocacao_grupo_historico
    ON alocacao_funcionario_grupo (grupo_producao_id, data_inicio DESC);